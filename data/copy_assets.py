"""
Copy Assets Script
Publishes the game image assets that the app actually renders into the public
folder as WebP.

The file list comes from asset_manifest.json, which is (re)generated by
build_asset_manifest.py from src/configs and the UI code references, so
assets the app never loads never land in public. The public folder is wiped
before copying so removed assets cannot pile up.

Encoding is hybrid: images up to 256 px (icons, headshots) are encoded
losslessly, larger artwork (formation/pile art) uses lossy quality 90 to keep
the app bundle small.
"""

import json
import shutil
import sys
from pathlib import Path

from PIL import Image

# Fix emoji output on Windows consoles (cp1252)
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# Paths
DATA_DIR = Path(__file__).resolve().parent
ASSETS_ROOT = DATA_DIR / "wuwa-assets"
PUBLIC_ROOT = DATA_DIR.parent / "public" / "wuwa-assets"
MANIFEST_PATH = DATA_DIR / "asset_manifest.json"

# Encoding rules. libwebp's exhaustive method 6 is pathologically slow for the
# larger RGBA artwork in this Pillow build (2-6 s per file); method 5 is about
# 8x faster for ~1% more bytes, so the lossy branch uses 5.
LOSSLESS_MAX_DIM = 256
LOSSY_QUALITY = 90
LOSSY_METHOD = 5


def encode_webp(source, destination):
	"""Convert one source PNG to WebP. Returns "lossy" or "lossless"."""
	image = Image.open(source)
	if image.mode == "P" and "transparency" in image.info:
		image = image.convert("RGBA")
	elif image.mode not in ("RGB", "RGBA"):
		image = image.convert("RGBA" if "A" in image.mode else "RGB")

	destination.parent.mkdir(parents=True, exist_ok=True)
	if max(image.size) > LOSSLESS_MAX_DIM:
		image.save(destination, "WEBP", quality=LOSSY_QUALITY, method=LOSSY_METHOD)
		return "lossy"
	image.save(destination, "WEBP", lossless=True, method=6)
	return "lossless"


def copy_assets():
	"""Copy the assets referenced by the manifest to the public folder."""
	print("=" * 60)
	print("Copy Assets to Public Folder")
	print("=" * 60)
	print()

	# Regenerate the manifest so public always matches the current app code.
	import build_asset_manifest

	build_asset_manifest.main()
	print()

	files = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))["files"]

	if PUBLIC_ROOT.exists():
		stale = sum(1 for path in PUBLIC_ROOT.rglob("*") if path.is_file())
		shutil.rmtree(PUBLIC_ROOT)
		print(f"🗑 Removed existing public assets ({stale} files)")

	source_bytes = 0
	output_bytes = 0
	lossy_count = 0
	for index, relative in enumerate(files, start=1):
		source = ASSETS_ROOT / relative
		destination = (PUBLIC_ROOT / relative).with_suffix(".webp")

		if encode_webp(source, destination) == "lossy":
			lossy_count += 1
		source_bytes += source.stat().st_size
		output_bytes += destination.stat().st_size

		if index % 200 == 0 or index == len(files):
			print(f"   … converted {index}/{len(files)}")

	print()
	print("=" * 60)
	print("✓ Asset copy complete!")
	print(
		f"  Converted: {len(files)} PNGs -> WebP "
		f"({lossy_count} lossy, {len(files) - lossy_count} lossless)"
	)
	print(
		f"  Size:      {source_bytes / 1024 / 1024:.1f} MiB -> "
		f"{output_bytes / 1024 / 1024:.1f} MiB"
	)
	print("=" * 60)


def main():
	copy_assets()


if __name__ == "__main__":
	main()
